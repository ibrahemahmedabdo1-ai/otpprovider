import { db } from '@/lib/db';
import { requireUser } from '@/lib/auth';
import { getT } from '@/lib/i18n';
import { Card, PageHead, Field, Flash, StatusBadge, Badge, Empty, dt } from '@/components/ui';
import { Reveal } from '@/components/Reveal';
import { AutoRefresh, QrView, ConfirmButton } from '@/components/Client';
import { isOnline, HEARTBEAT_STALE_MS } from '@/lib/whatsapp';
import { fmtMoney } from '@/lib/ledger';
import { createDeviceAction, updateDeviceAction, deviceCommandAction, testMessageAction, pauseDeviceAction, rotateDeviceTokenAction, deleteDeviceAction } from '@/app/actions/admin';
import { getServiceConfig } from '@/lib/services';

export const dynamic = 'force-dynamic';
export const metadata = { title: 'WhatsApp devices' };

export default async function WhatsApp({ searchParams }: { searchParams: { ok?: string; err?: string } }) {
  await requireUser({ perm: 'whatsapp.manage' });
  const { t } = getT();
  const since = new Date(Date.now() - 30 * 864e5);
  const [devices, stats, recent, cfg] = await Promise.all([
    db.whatsAppDevice.findMany({ orderBy: { priority: 'asc' }, include: { commands: { orderBy: { createdAt: 'desc' }, take: 3 } } }),
    db.messageRequest.groupBy({ by: ['deviceId', 'status'], where: { service: 'WHATSAPP_OTP', createdAt: { gte: since }, deviceId: { not: null } }, _count: { _all: true } }),
    db.messageRequest.findMany({ where: { service: 'WHATSAPP_OTP' }, orderBy: { createdAt: 'desc' }, take: 15, include: { device: { select: { label: true } }, tenant: { select: { name: true } } } }),
    getServiceConfig('WHATSAPP_OTP'),
  ]);
  const n = (id: string, sts: string[]) => stats.filter((s) => s.deviceId === id && sts.includes(s.status)).reduce((a, s) => a + s._count._all, 0);
  const today = new Date().toISOString().slice(0, 10);
  return (
    <>
      <AutoRefresh seconds={4} />
      <PageHead title={t('WhatsApp devices')} sub={t('Link phones by QR code, switch between them and control every device from here.')} actions={<span className="flex items-center gap-2 text-sm"><StatusBadge s={cfg.state} /> OTP</span>} />
      <Flash ok={searchParams.ok} err={searchParams.err} />
      <Reveal />
      <Card className="mb-4" >
        <p className="text-sm" style={{ color: 'var(--muted)' }}>
          {t('Linked-device (QR) sessions can expire, disconnect or be revoked by WhatsApp at any time, and are not the official Business Platform. Use a dedicated number, keep volume modest, and plan to move to the WhatsApp Cloud API for guaranteed production use. The QR below is generated by the real gateway session; nothing is shown when no session exists.')}
        </p>
      </Card>
      <div className="grid gap-4 lg:grid-cols-2 mb-6">
        {devices.length === 0 && <Card className="lg:col-span-2"><Empty text={t('No devices yet. Add one below, run the gateway with its token, then scan the QR code.')} /></Card>}
        {devices.map((d) => {
          const online = isOnline(d);
          const stale = d.lastHeartbeat ? Date.now() - d.lastHeartbeat.getTime() > HEARTBEAT_STALE_MS : true;
          const shownStatus = d.status === 'CONNECTED' && stale ? 'DISCONNECTED' : d.status;
          const qrFresh = d.status === 'PAIRING' && d.qr && d.qrAt && Date.now() - d.qrAt.getTime() < 90000 && !stale;
          const sent = d.sentTodayDate === today ? d.sentToday : 0;
          return (
            <Card key={d.id}>
              <div className="flex justify-between items-start gap-2 mb-3">
                <div><div className="font-semibold flex items-center gap-2">{online && <span className="pulse-dot" />}{d.label}</div><div className="text-sm" style={{ color: 'var(--muted)' }}>{d.phone ?? t('No number linked yet')}</div></div>
                <div className="flex gap-1 flex-wrap justify-end"><StatusBadge s={shownStatus} />{!d.enabled && <Badge tone="bad">{t('routing off')}</Badge>}</div>
              </div>
              {qrFresh && (<div className="flex flex-col items-center gap-2 mb-4"><QrView value={d.qr!} /><p className="text-xs text-center" style={{ color: 'var(--muted)' }}>{t('WhatsApp → Settings → Linked devices → Link a device. The code refreshes automatically.')}</p></div>)}
              {d.status === 'PAIRING' && !qrFresh && <p className="text-sm mb-3" style={{ color: 'var(--warn)' }}>{t('Waiting for the gateway to produce a QR code. Make sure it is running.')}</p>}
              <dl className="grid grid-cols-2 gap-x-4 gap-y-1 text-xs mb-3">
                <dt style={{ color: 'var(--muted)' }}>{t('Last heartbeat')}</dt><dd>{dt(d.lastHeartbeat)}</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('Last connected')}</dt><dd>{dt(d.lastConnectedAt)}</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('Last test message')}</dt><dd>{dt(d.lastTestAt)}</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('Gateway version')}</dt><dd>{d.gatewayVersion ?? '—'}</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('Sent today')}</dt><dd>{sent} / {d.dailyLimit}</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('30 days')}</dt><dd>{n(d.id, ['DELIVERED', 'READ'])} {t('delivered')} · {n(d.id, ['SUBMITTED', 'SENT'])} {t('sent')} · {n(d.id, ['FAILED', 'REJECTED', 'EXPIRED'])} {t('failed')} · {n(d.id, ['UNKNOWN_OUTCOME'])} ?</dd>
                <dt style={{ color: 'var(--muted)' }}>{t('Priority')}</dt><dd>{d.priority}</dd>
              </dl>
              {d.lastError && <p className="text-xs mb-3" style={{ color: 'var(--bad)' }}>{t('Last error')}: {d.lastError}</p>}
              <div className="flex flex-wrap gap-2 mb-3">
                {(['REFRESH_QR', 'RECONNECT', 'DISCONNECT'] as const).map((c) => (
                  <form key={c} action={deviceCommandAction}><input type="hidden" name="id" value={d.id} /><input type="hidden" name="type" value={c} />
                    <ConfirmButton className={`btn btn-sm ${c === 'DISCONNECT' ? 'btn-danger' : 'btn-ghost'}`} message={`${c}?`}>{c === 'REFRESH_QR' ? t('New QR') : c === 'RECONNECT' ? t('Reconnect') : t('Disconnect')}</ConfirmButton></form>))}
                <form action={pauseDeviceAction}><input type="hidden" name="id" value={d.id} /><input type="hidden" name="pause" value={d.status === 'PAUSED' ? '0' : '1'} /><button className="btn btn-ghost btn-sm">{d.status === 'PAUSED' ? t('Resume') : t('Pause')}</button></form>
              </div>
              <form action={testMessageAction} className="flex gap-2 mb-3"><input type="hidden" name="id" value={d.id} /><input className="input" name="to" placeholder="+201234567890" required /><button className="btn btn-ghost btn-sm" disabled={shownStatus !== 'CONNECTED'}>{t('Send test')}</button></form>
              <details className="text-sm"><summary className="cursor-pointer font-medium">{t('Edit device')}</summary>
                <form action={updateDeviceAction} className="grid grid-cols-2 gap-3 mt-3"><input type="hidden" name="id" value={d.id} />
                  <Field label={t('Label')}><input className="input" name="label" defaultValue={d.label} /></Field>
                  <Field label={t('Priority (1 = first)')}><input className="input" type="number" name="priority" min={1} defaultValue={d.priority} /></Field>
                  <Field label={t('Daily limit')}><input className="input" type="number" name="dailyLimit" min={1} defaultValue={d.dailyLimit} /></Field>
                  <label className="flex gap-2 items-end pb-2"><input type="checkbox" name="enabled" defaultChecked={d.enabled} />{t('Use for routing')}</label>
                  <div className="col-span-2 flex gap-2 flex-wrap"><button className="btn btn-primary btn-sm">{t('Save')}</button></div>
                </form>
                <div className="flex gap-2 mt-3">
                  <form action={rotateDeviceTokenAction}><input type="hidden" name="id" value={d.id} /><ConfirmButton className="btn btn-ghost btn-sm" message={t('Rotate the token? The running gateway will stop working until updated.')}>{t('Rotate token')}</ConfirmButton></form>
                  <form action={deleteDeviceAction}><input type="hidden" name="id" value={d.id} /><ConfirmButton className="btn btn-danger btn-sm" message={t('Delete this device?')}>{t('Delete')}</ConfirmButton></form>
                </div>
              </details>
            </Card>);
        })}
      </div>
      <Card className="mb-6">
        <h2 className="font-semibold mb-3">{t('Add a device')}</h2>
        <form action={createDeviceAction} className="grid gap-3 md:grid-cols-4 items-end">
          <Field label={t('Label')}><input className="input" name="label" placeholder="My phone" required /></Field>
          <Field label={t('Priority')}><input className="input" type="number" name="priority" min={1} defaultValue={devices.length + 1} /></Field>
          <Field label={t('Daily limit')}><input className="input" type="number" name="dailyLimit" min={1} defaultValue={500} /></Field>
          <button className="btn btn-primary">{t('Create & get token')}</button>
        </form>
      </Card>
      <Card>
        <h2 className="font-semibold mb-3">{t('Recent WhatsApp requests')}</h2>
        {recent.length === 0 ? <Empty text="—" /> : (
          <div className="overflow-x-auto"><table className="table"><thead><tr><th>{t('Time')}</th><th>{t('Customer')}</th><th>{t('Sender device')}</th><th>{t('Recipient')}</th><th>{t('Status')}</th><th>{t('Error')}</th><th>{t('Charge')}</th></tr></thead><tbody>
            {recent.map((m) => <tr key={m.id}><td>{dt(m.createdAt)}</td><td>{m.tenant.name}</td><td>{m.device?.label ?? '—'} {m.senderLabel ?? ''}</td><td>{m.recipient}</td><td><StatusBadge s={m.status} /></td><td>{m.errorMessage ?? m.errorCode ?? '—'}</td><td>{fmtMoney(m.charge)}</td></tr>)}
          </tbody></table></div>)}
      </Card>
    </>
  );
}
